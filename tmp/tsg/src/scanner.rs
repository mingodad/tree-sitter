//! `tsg` writes `scanner.c` for the external tokens it can generate itself.
//!
//! tree-sitter's native lexer is a DFA over the token patterns, with the lexer
//! state derived from the parse state — no stack, and no state that outlives a
//! token. Anything that has to remember nesting (`{ … }` action bodies, `%{ … %}`
//! prologues) therefore has to be an external token whose recogniser is C. That
//! C is the one part of a grammar that `grammar.json` cannot describe, which is
//! why a grammar with externals normally carries a hand-written `scanner.c`
//! beside it.
//!
//! `%external NAME = delimited('{', '}');` removes that split: the region is one
//! token, so the depth is a *local* of the scan function, and the file written
//! here is a build artifact of the `.tsg` — exactly like `parser.c`. Nothing is
//! serialized between tokens, so incremental parsing is unaffected.
//!
//! What this deliberately does not do: understand strings or comments inside the
//! region. A `}` in a string literal counts like any other character. If a
//! grammar needs that, it needs a hand-written scanner, and the note `tsg` prints
//! says so rather than pretending the generated one is exact.

use crate::parser::Delimited;

/// First line of every file this module writes. `tsg` refuses to overwrite a
/// `scanner.c` that does not begin with it.
pub const MARKER: &str = "// Generated by tsg";

/// The C source for `src/scanner.c`.
///
/// `externals` is the grammar's external token list *in order*: the generator
/// refers to them by index in `EXTERNAL_TOKEN_COUNT`, so the enum here has to
/// follow the same order. Externals without a `delimited(…)` declaration get an
/// entry too (the order matters) but their branch in `scan` never matches.
pub fn source(grammar: &str, externals: &[String], scanners: &[Delimited]) -> String {
    let prefix = format!("tree_sitter_{grammar}_external_scanner");
    let mut out = String::new();

    out.push_str(MARKER);
    out.push_str(" from `%external NAME = delimited(open, close)`;\n");
    out.push_str("// Do not edit: change the `.tsg` and re-run `tsg <grammar>.tsg -o src/grammar.json`.\n\n");
    out.push_str("#include <stdbool.h>\n#include <stdint.h>\n#include <stdlib.h>\n\n");
    out.push_str("#include \"tree_sitter/parser.h\"\n\n");

    out.push_str("// The order is the order of `externals` in grammar.json; the generator\n");
    out.push_str("// refers to these by index.\nenum tsg_external_tokens {\n");
    for (index, name) in externals.iter().enumerate() {
        out.push_str(&format!("  {} = {index},\n", c_identifier(name)));
    }
    out.push_str("};\n\n");

    out.push_str("typedef struct {\n  char unused;\n} TsgScanner;\n\n");

    out.push_str(&format!(
        "void *{prefix}_create(void) {{\n  return calloc(1, sizeof(TsgScanner));\n}}\n\n"
    ));
    out.push_str(&format!(
        "void {prefix}_destroy(void *payload) {{\n  free(payload);\n}}\n\n"
    ));
    out.push_str("// No state outlives a call: a delimited region is one token, so its depth is a\n");
    out.push_str("// local of `tsg_scan_delimited`. Nothing to save between tokens.\n");
    out.push_str(&format!(
        "unsigned {prefix}_serialize(void *payload, char *buffer) {{\n  \
         (void)payload;\n  (void)buffer;\n  return 0;\n}}\n\n"
    ));
    out.push_str(&format!(
        "void {prefix}_deserialize(void *payload, const char *buffer, unsigned length) {{\n  \
         (void)payload;\n  (void)buffer;\n  (void)length;\n}}\n\n"
    ));

    out.push_str(
        "// One region: the opening character, then everything up to the closing one\n\
         // that takes the nesting depth back to zero. The whole region is the token.\n\
         // An unterminated region ends at end of input and is left to the parser to\n\
         // reject, rather than silently matching a shorter token.\n\
         static bool tsg_is_space(int32_t character) {\n\
         \x20 return character == ' ' || character == '\\t' || character == '\\n' ||\n\
         \x20        character == '\\r' || character == '\\f' || character == '\\v';\n\
         }\n\n\
         static bool tsg_scan_delimited(TSLexer *lexer, int32_t open, int32_t close) {\n\
         \x20 // The scanner runs before tree-sitter skips extras, so the whitespace\n\
         \x20 // between the last token and the region has to be skipped here. `true`\n\
         \x20 // means \"not part of the token\".\n\
         \x20 while (tsg_is_space(lexer->lookahead)) lexer->advance(lexer, true);\n\
         \x20 if (lexer->lookahead != open) return false;\n\
         \x20 int32_t depth = 0;\n\
         \x20 for (;;) {\n\
         \x20   int32_t character = lexer->lookahead;\n\
         \x20   if (character == 0) return true;\n\
         \x20   if (character == open) {\n\
         \x20     depth += 1;\n\
         \x20   } else if (character == close) {\n\
         \x20     depth -= 1;\n\
         \x20     if (depth == 0) {\n\
         \x20       lexer->advance(lexer, false);\n\
         \x20       return true;\n\
         \x20     }\n\
         \x20   }\n\
         \x20   lexer->advance(lexer, false);\n\
         \x20 }\n\
         }\n\n",
    );

    out.push_str(&format!(
        "bool {prefix}_scan(void *payload, TSLexer *lexer, const bool *valid_symbols) {{\n  (void)payload;\n"
    ));
    for external in externals {
        let Some(scanner) = scanners.iter().find(|scanner| &scanner.name == external) else {
            continue;
        };
        let token = c_identifier(external);
        out.push_str(&format!(
            "  if (valid_symbols[{token}] && tsg_scan_delimited(lexer, {}, {})) {{\n    \
             lexer->result_symbol = {token};\n    return true;\n  }}\n",
            c_character(scanner.open),
            c_character(scanner.close)
        ));
    }
    out.push_str("  return false;\n}\n");

    out
}

/// The external tokens that have no `delimited(…)` declaration, in order. Their
/// scanner has to be hand-written; `tsg` names them instead of letting the
/// grammar fail to link with an unexplained undefined symbol.
pub fn without_scanner(externals: &[String], scanners: &[Delimited]) -> Vec<String> {
    externals
        .iter()
        .filter(|external| !scanners.iter().any(|scanner| &scanner.name == *external))
        .cloned()
        .collect()
}

/// A C identifier for a token name. `grammar.json` token names are already
/// close to this; the replacement only exists so a name in a `.tsg` can never
/// produce a scanner that does not compile.
fn c_identifier(name: &str) -> String {
    let mut out: String = name
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || character == '_' {
                character
            } else {
                '_'
            }
        })
        .collect();
    if out.is_empty() || out.starts_with(|character: char| character.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

/// A character as a C expression. Numeric, because quoting is the one thing a
/// generator can get wrong invisibly: `'\''`, `'\\'` and a newline all need
/// different escaping, and the comment carries the readable form either way.
fn c_character(character: char) -> String {
    let shown = match character {
        '\n' => "\\n".to_owned(),
        '\r' => "\\r".to_owned(),
        '\t' => "\\t".to_owned(),
        other => other.to_string(),
    };
    format!("0x{:X} /* {shown} */", character as u32)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::lexer::Span;

    fn delimited(name: &str, open: char, close: char) -> Delimited {
        Delimited {
            name: name.to_owned(),
            open,
            close,
            span: Span::new(0, 0),
        }
    }

    #[test]
    fn names_the_scanner_functions_after_the_grammar() {
        let externals = vec!["action_code".to_owned()];
        let source = source("bison", &externals, &[delimited("action_code", '{', '}')]);
        assert!(source.starts_with("// Generated by tsg"));
        assert!(source.contains("void *tree_sitter_bison_external_scanner_create(void)"));
        assert!(source.contains("bool tree_sitter_bison_external_scanner_scan("));
    }

    #[test]
    fn keeps_the_external_order_because_the_generator_indexes_it() {
        let externals = vec!["first".to_owned(), "second".to_owned()];
        let source = source(
            "x",
            &externals,
            &[
                delimited("second", '[', ']'),
                delimited("first", '{', '}'),
            ],
        );
        let first = source.find("first = 0,").expect("first is index 0");
        let second = source.find("second = 1,").expect("second is index 1");
        assert!(first < second);
        // The scan branches follow the same order, not the declaration order.
        let scan_at = source.find("_scan(void").expect("scan function");
        let first_at = source[scan_at..].find("valid_symbols[first]").expect("first");
        let second_at = source[scan_at..]
            .find("valid_symbols[second]")
            .expect("second");
        assert!(first_at < second_at);
    }

    #[test]
    fn an_external_without_a_delimiter_has_no_branch_but_keeps_its_index() {
        let externals = vec!["heredoc".to_owned(), "action".to_owned()];
        let source = source("x", &externals, &[delimited("action", '{', '}')]);
        assert!(source.contains("heredoc = 0,"));
        assert!(source.contains("action = 1,"));
        assert!(!source.contains("valid_symbols[heredoc]"));
        assert_eq!(
            without_scanner(&externals, &[delimited("action", '{', '}')]),
            vec!["heredoc".to_owned()]
        );
    }

    #[test]
    fn a_delimiter_is_written_as_a_number_with_the_character_beside_it() {
        let source = source("x", &["s".to_owned()], &[delimited("s", '\'', '\\')]);
        assert!(source.contains("0x27 /* ' */"), "{source}");
        assert!(source.contains("0x5C /* \\ */"), "{source}");
    }
}
